-- 会话标识及关联数据。
CREATE TABLE IF NOT EXISTS agent_session (
    id varchar(36) PRIMARY KEY,
    agent_key text NOT NULL,
    active_run_id varchar(36),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON COLUMN agent_session.id IS '会话标识';
COMMENT ON COLUMN agent_session.agent_key IS '会话绑定的 Agent';
COMMENT ON COLUMN agent_session.active_run_id IS '当前占用会话的运行';
COMMENT ON COLUMN agent_session.created_at IS '创建时间';
COMMENT ON COLUMN agent_session.updated_at IS '最近状态更新时间';

-- 运行标识及关联数据。
CREATE TABLE IF NOT EXISTS agent_run (
    id varchar(36) PRIMARY KEY,
    session_id varchar(36) NOT NULL REFERENCES agent_session(id),
    turn_no integer NOT NULL,
    status text NOT NULL CHECK (status IN ('RUNNING','SUCCEEDED','FAILED')),
    failure text,
    started_at timestamptz NOT NULL DEFAULT now(),
    ended_at timestamptz,
    UNIQUE (session_id, turn_no)
);
COMMENT ON COLUMN agent_run.id IS '运行标识';
COMMENT ON COLUMN agent_run.session_id IS '所属会话';
COMMENT ON COLUMN agent_run.turn_no IS '会话内轮次';
COMMENT ON COLUMN agent_run.status IS '运行状态';
COMMENT ON COLUMN agent_run.failure IS '失败原因';
COMMENT ON COLUMN agent_run.started_at IS '开始时间';
COMMENT ON COLUMN agent_run.ended_at IS '结束时间';

-- 所属运行及关联数据。
CREATE TABLE IF NOT EXISTS agent_message (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id varchar(36) NOT NULL REFERENCES agent_run(id),
    seq integer NOT NULL,
    payload jsonb NOT NULL,
    UNIQUE (run_id, seq)
);
COMMENT ON COLUMN agent_message.run_id IS '所属运行';
COMMENT ON COLUMN agent_message.id IS '供 MyBatis-Plus 使用的消息主键';
COMMENT ON COLUMN agent_message.seq IS '运行内消息顺序';
COMMENT ON COLUMN agent_message.payload IS '完整角色消息，包含内容、工具调用及结果';

-- 压缩只更新模型视图，不替换原始聊天消息。
CREATE TABLE IF NOT EXISTS agent_context_checkpoint (
    session_id varchar(36) PRIMARY KEY REFERENCES agent_session(id),
    through_turn integer NOT NULL CHECK (through_turn > 0),
    summary text NOT NULL,
    format_version integer NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (session_id, through_turn) REFERENCES agent_run(session_id, turn_no)
);
COMMENT ON COLUMN agent_context_checkpoint.session_id IS '所属会话';
COMMENT ON COLUMN agent_context_checkpoint.through_turn IS '摘要覆盖的最后一个成功轮次';
COMMENT ON COLUMN agent_context_checkpoint.summary IS '仅供模型参考的会话摘要';
COMMENT ON COLUMN agent_context_checkpoint.format_version IS '摘要格式版本';
COMMENT ON COLUMN agent_context_checkpoint.updated_at IS '检查点更新时间';

ALTER TABLE agent_run ADD COLUMN IF NOT EXISTS steer_close_reason text;
COMMENT ON COLUMN agent_run.steer_close_reason IS '运行中关闭补充入口的原因；终态由 status 派生';

CREATE TABLE IF NOT EXISTS agent_run_steer (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id varchar(36) NOT NULL REFERENCES agent_run(id),
    client_message_id varchar(36) NOT NULL,
    message text NOT NULL,
    message_seq integer,
    received_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (run_id, client_message_id),
    UNIQUE (run_id, message_seq),
    FOREIGN KEY (run_id, message_seq) REFERENCES agent_message(run_id, seq)
);
CREATE INDEX IF NOT EXISTS agent_run_steer_unread_idx
    ON agent_run_steer (run_id, id) WHERE message_seq IS NULL;
COMMENT ON COLUMN agent_run_steer.id IS '按目标 Run 行锁分配的接收顺序';
COMMENT ON COLUMN agent_run_steer.run_id IS '补充所属运行';
COMMENT ON COLUMN agent_run_steer.client_message_id IS '客户端幂等 UUID';
COMMENT ON COLUMN agent_run_steer.message IS '未经改写的用户补充';
COMMENT ON COLUMN agent_run_steer.message_seq IS '纳入后的真实消息序号';
COMMENT ON COLUMN agent_run_steer.received_at IS '收件时间';

-- 固定用户的每个 Agent 只有一份跨会话记忆正文，无分片或条目表。
CREATE TABLE IF NOT EXISTS agent_memory (
    agent_key text PRIMARY KEY,
    content text NOT NULL CHECK (octet_length(content) <= 2000),
    revision bigint NOT NULL CHECK (revision > 0)
);
COMMENT ON COLUMN agent_memory.agent_key IS '由运行所属会话推导的 Agent 标识';
COMMENT ON COLUMN agent_memory.content IS '整段长期记忆原文';
COMMENT ON COLUMN agent_memory.revision IS '正文发生变化时递增的版本';
