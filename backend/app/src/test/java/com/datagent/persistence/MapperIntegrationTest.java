package com.datagent.persistence;

import static org.assertj.core.api.Assertions.assertThat;

import com.baomidou.mybatisplus.annotation.IdType;
import com.baomidou.mybatisplus.annotation.TableId;
import com.baomidou.mybatisplus.annotation.TableName;
import com.baomidou.mybatisplus.core.mapper.BaseMapper;
import com.baomidou.mybatisplus.core.toolkit.Wrappers;
import com.datagent.persistence.entity.BaseEntity;
import lombok.Getter;
import lombok.Setter;
import org.apache.ibatis.annotations.Mapper;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.jdbc.Sql;
import org.springframework.transaction.annotation.Transactional;

/** 验证 Spring 自动发现 Mapper，并能通过 Lombok 生成的访问器读写数据库。 */
@SpringBootTest(properties = "spring.datasource.url=jdbc:h2:mem:mapper_integration")
@Transactional
class MapperIntegrationTest {

    static final String TABLE = "mapper_probe";
    private static final String CREATE_TABLE = "CREATE TABLE IF NOT EXISTS " + TABLE
            + " (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label VARCHAR(64),"
            + " tenent_id BIGINT DEFAULT 1, create_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,"
            + " update_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP, delete_at TIMESTAMP WITH TIME ZONE,"
            + " is_deleted BOOLEAN NOT NULL DEFAULT FALSE)";
    private static final String INITIAL_LABEL = "initial";
    private static final String UPDATED_LABEL = "updated";

    @Test
    @Sql(statements = CREATE_TABLE)
    void supportsCrudAndLambdaQueries(@Autowired ProbeMapper mapper) {
        // 插入测试记录，验证主键回填和 Lombok 访问器。
        Probe probe = new Probe();
        probe.setLabel(INITIAL_LABEL);
        assertThat(mapper.insert(probe)).isEqualTo(1);
        assertThat(probe.getId()).isNotNull();

        // 通过实体属性构造查询条件，验证数据库列与生成的 getter 可以配合使用。
        Probe stored = mapper.selectOne(Wrappers.<Probe>lambdaQuery().eq(Probe::getLabel, INITIAL_LABEL));
        assertThat(stored.getId()).isEqualTo(probe.getId());

        // 更新后重新读取，再验证删除结果。
        stored.setLabel(UPDATED_LABEL);
        assertThat(mapper.updateById(stored)).isEqualTo(1);
        assertThat(mapper.selectById(stored.getId()).getLabel()).isEqualTo(UPDATED_LABEL);
        assertThat(mapper.deleteById(stored.getId())).isEqualTo(1);
        assertThat(mapper.selectById(stored.getId())).isNull();
    }

    /** 仅供集成测试使用的持久化实体。 */
    @Getter
    @Setter
    @TableName(TABLE)
    static class Probe extends BaseEntity {
        /** 数据库生成的记录标识，用于验证主键回填。 */
        @TableId(type = IdType.AUTO)
        private Long id;

        /** 用于验证条件查询和更新的测试值。 */
        private String label;
    }

    /** 由 MyBatis-Plus 生成通用 CRUD 实现。 */
    @Mapper
    interface ProbeMapper extends BaseMapper<Probe> {
    }
}
